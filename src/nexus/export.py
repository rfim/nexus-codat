"""Export what the site shows from the run that just finished: products, lineage, evidence, history.

Everything under assets/data/ is regenerated by scripts/build.sh; nothing on the site is typed by hand.
"""
import json
from datetime import date, datetime
from decimal import Decimal

from nexus import contracts, semantic
from nexus.spark import ROOT, TARGET, get_spark, table

DATA = ROOT / "assets" / "data"


def _clean(v):
    if isinstance(v, Decimal):
        return float(v)
    if isinstance(v, (date, datetime)):
        return v.isoformat()
    if isinstance(v, dict):
        return {k: _clean(x) for k, x in v.items()}
    if isinstance(v, list):
        return [_clean(x) for x in v]
    return v


def _rows(spark, sql: str) -> list[dict]:
    return [_clean(r.asDict(recursive=True)) for r in spark.sql(sql).collect()]


def _history(spark, layer: str, name: str) -> list[dict]:
    return [{"version": r["version"], "operation": r["operation"],
             "rows_out": (r["operationMetrics"] or {}).get("numOutputRows"),
             "rows_updated": (r["operationMetrics"] or {}).get("numTargetRowsUpdated"),
             "rows_inserted": (r["operationMetrics"] or {}).get("numTargetRowsInserted")}
            for r in spark.sql(f"DESCRIBE HISTORY {table(layer, name)}").orderBy("version").collect()]


def export(log: dict | None = None) -> dict:
    spark = get_spark()
    log = log or json.loads((TARGET / "run_log.json").read_text())
    (DATA / "products").mkdir(parents=True, exist_ok=True)

    products = {}
    for c in contracts.load_products():
        rows = _rows(spark, f"SELECT * FROM {table('gold', c['product'])} ORDER BY ALL")
        (DATA / "products" / f"{c['product']}.json").write_text(json.dumps(rows))
        products[c["product"]] = len(rows)

    checks = {c["product"]: c for c in log["contracts"]}
    upstream = {
        "insights_revenue_monthly": ["gold.fct_invoice", "silver.invoice", "silver.account_mapping",
                                     "bronze.ledgerone_invoice", "bronze.bookwise_invoice",
                                     "bronze.orbiterp_invoice", "bronze.account", "silver.company_entitlement"],
        "insights_cash_flow_monthly": ["silver.bank_transaction", "silver.bank_balance", "bronze.bank_transaction",
                                       "bronze.bank_balance", "silver.company_entitlement"],
        "insights_dso_monthly": ["gold.fct_invoice", "silver.invoice", "bronze.ledgerone_invoice",
                                 "bronze.bookwise_invoice", "bronze.orbiterp_invoice", "silver.company_entitlement"],
        "insights_commerce_monthly": ["silver.commerce_payout", "silver.bank_transaction", "bronze.commerce_payout",
                                      "bronze.bank_transaction", "silver.company_entitlement"],
        "insights_data_completeness": ["gold.fct_invoice", "silver.invoice_quarantine", "silver.bank_transaction",
                                       "silver.company", "silver.company_entitlement"],
    }
    lineage = {p: {"product": f"gold.{p}", "upstream": up,
                   "version": int(spark.sql(f"DESCRIBE HISTORY {table('gold', p)}").agg({"version": "max"}).first()[0]),
                   "checks_passed": checks[p]["passed"], "checks_total": checks[p]["total"],
                   "checks": [{"check": r["check"], "status": r["status"], "failing_rows": r["failing_rows"]}
                              for r in checks[p]["results"]],
                   "contract": f"contracts/products/{p}.yml"} for p, up in upstream.items()}
    (DATA / "lineage.json").write_text(json.dumps(lineage, indent=2))
    (DATA / "catalogue.json").write_text(json.dumps(list(semantic.catalogue().values()), indent=2))

    rev = table("gold", "insights_revenue_monthly")
    evidence = {
        "canonical_examples": {
            p: {"raw": _rows(spark, f"SELECT * EXCEPT (_ingested_at, _source_file) FROM {table('bronze', p + '_invoice')} "
                                    f"ORDER BY 1, 2 LIMIT 1")[0],
                "canonical": _rows(spark, f"SELECT * EXCEPT (_ingested_at) FROM {table('silver', 'invoice')} "
                                          f"WHERE source_platform = '{p}' ORDER BY company_id, source_invoice_id LIMIT 1")[0]}
            for p in ("ledgerone", "bookwise", "orbiterp")},
        "quarantine": _rows(spark, f"SELECT source_platform, company_id, source_invoice_id, status, currency, issue_date, "
                                   f"due_date, _failed_rules FROM {table('silver', 'invoice_quarantine')} ORDER BY ALL"),
        "scd2_c103": _rows(spark, f"SELECT company_id, account_id, account_name, account_type, valid_from, valid_to, "
                                  f"is_current FROM {table('silver', 'account_mapping')} WHERE company_id = 'C-103' "
                                  f"AND account_id = '4100' ORDER BY valid_from"),
        "c103_revenue": _rows(spark, f"SELECT month, revenue FROM {rev} WHERE company_id = 'C-103' ORDER BY month"),
        "restatement": _rows(spark, f"""
            WITH issued AS (SELECT customer_id, company_id, month, revenue FROM {rev} VERSION AS OF 0),
                 now AS (SELECT customer_id, company_id, month, revenue FROM {rev})
            SELECT n.customer_id, n.company_id, n.month, i.revenue AS issued, n.revenue AS now,
                   round(n.revenue - coalesce(i.revenue, 0), 2) AS delta
            FROM now n LEFT JOIN issued i USING (customer_id, company_id, month)
            WHERE n.revenue <> coalesce(i.revenue, 0) ORDER BY abs(n.revenue - coalesce(i.revenue, 0)) DESC"""),
        "entitlements": _rows(spark, f"SELECT * FROM {table('silver', 'company_entitlement')} ORDER BY ALL"),
        "companies": _rows(spark, f"SELECT company_id, company_name, industry, platform, currency "
                                  f"FROM {table('silver', 'company')} ORDER BY 1"),
        "break_c107": _rows(spark, f"SELECT company_id, txn_id, booked_date, amount, description, category, sync_seq "
                                   f"FROM {table('silver', 'bank_transaction')} WHERE company_id = 'C-107' "
                                   f"AND amount = 1250.00 ORDER BY booked_date"),
        "break_dupes": _rows(spark, f"SELECT company_id, booked_date, amount, count(*) AS n, collect_list(txn_id) AS txn_ids "
                                    f"FROM {table('silver', 'bank_transaction')} WHERE amount > 0 "
                                    f"GROUP BY ALL HAVING count(*) > 1 ORDER BY ALL"),
        "c107_balance": _rows(spark, f"SELECT * FROM {table('silver', 'bank_balance')} WHERE company_id = 'C-107'"),
        "daily_volume_c107": _rows(spark, f"SELECT booked_date, count(*) AS n FROM {table('silver', 'bank_transaction')} "
                                          f"WHERE company_id = 'C-107' GROUP BY 1 ORDER BY 1"),
    }
    history = {f"{l}.{n}": _history(spark, l, n) for l, n in (
        ("bronze", "ledgerone_invoice"), ("bronze", "bank_transaction"), ("gold", "fct_invoice"),
        ("gold", "insights_revenue_monthly"))}
    compiled = {c["product"]: {"checks": [{"check": k["check"], "sql": k["sql"]} for k in contracts.compile_checks(c)],
                               "governance": contracts.compile_governance(c),
                               "expectations": contracts.compile_expectations(c)} for c in contracts.load_products()}
    site = {"run": {k: log[k] for k in ("feeds", "bronze", "bronze_after_replay", "silver", "gold_fact", "as_issued",
                                         "late_batch", "current", "tasks", "seconds")},
            "contracts": [{k: c[k] for k in ("product", "owner", "passed", "total")} |
                          {"results": [{x: r[x] for x in ("check", "kind", "status", "failing_rows", "sample")}
                                       for r in c["results"]]} for c in log["contracts"]],
            "products": products, "evidence": evidence, "history": history, "compiled": compiled,
            "gx": log.get("gx", []), "incident": log.get("incident")}
    (DATA / "site.json").write_text(json.dumps(_clean(site), indent=1, default=str))
    return site


if __name__ == "__main__":
    export()
    print("wrote", DATA)
